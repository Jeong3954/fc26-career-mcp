#!/usr/bin/env python3
"""Generate bridge/fc26cm_bridge_autorun.lua from bridge/fc26cm_bridge.lua.

The two files differ in exactly one line: `local AUTORUN = false` -> `local AUTORUN = true`.
The autorun copy only registers its event handler when Live Editor loads it at game start; the first read
happens on a career event once the career hub has settled. Run after every change of the manual bridge.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "bridge", "fc26cm_bridge.lua")
DST = os.path.join(HERE, "..", "bridge", "fc26cm_bridge_autorun.lua")
OLD = "local AUTORUN = false\n"
NEW = "local AUTORUN = true -- generated by tools/build_autorun.py: do not edit, edit fc26cm_bridge.lua\n"


def build(src=SRC, dst=DST):
    text = open(src, encoding="utf-8").read()
    if text.count(OLD) != 1:
        raise SystemExit("expected exactly one '%s' line in %s" % (OLD.strip(), src))
    out = text.replace(OLD, NEW)
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    return dst


if __name__ == "__main__":
    print("written", build(*sys.argv[1:3]))
