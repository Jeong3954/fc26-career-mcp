"""Bridge crash guard (1.0.1): every memory read goes through MEM, and MEM rejects bad addresses before LE's
native read. The behaviour part runs the MEM block in a real Lua (lupa) when it is installed."""
import os
import re
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
BRIDGE = os.path.join(HERE, "..", "bridge", "fc26cm_bridge.lua")
AUTORUN = os.path.join(HERE, "..", "bridge", "fc26cm_bridge_autorun.lua")


def src(path=BRIDGE):
    with open(path, encoding="utf-8") as f:
        return f.read()


class StaticGuardTest(unittest.TestCase):
    def test_no_direct_memory_reads(self):
        s = src()
        self.assertNotIn("MEMORY:Read", s)
        self.assertIn("MEM:ReadPointer", s)

    def test_gate_and_kill_switch(self):
        s = src()
        for needle in ("local function memory_gate()", "disable_memory", "MEM_SETTLE_S", "multi_day_sim",
                       "world_due = true", 'write_snapshot("memory_refresh", false)', "mem_tick()"):
            self.assertIn(needle, s)
        # DAY_PASSED no longer writes world.json (memory) in its own tick
        self.assertNotIn('write_world("day_passed")', s)

    def test_autorun_in_sync(self):
        a, m = src(AUTORUN), src()
        self.assertEqual(a.replace(
            "local AUTORUN = true -- generated by tools/build_autorun.py: do not edit, edit fc26cm_bridge.lua",
            "local AUTORUN = false"), m)


try:
    import lupa  # noqa: F401
except ImportError:  # pragma: no cover
    lupa = None


@unittest.skipIf(lupa is None, "lupa not installed")
class MemBlockTest(unittest.TestCase):
    def setUp(self):
        s = src()
        block = s[s.index("local ADDR_LO"):s.index("-- Memory gate:")]
        self.lua = lupa.LuaRuntime()
        self.lua.execute("""
            calls = {}
            MEMORY = {}
            function MEMORY:ReadQwordValue() return 0 end
            function MEMORY:ReadPointer(a) calls[#calls + 1] = a; return ptr_value end
            function MEMORY:ReadShort(a) calls[#calls + 1] = a; return 7 end
            function MEMORY:ReadInt(a) calls[#calls + 1] = a; return int_value end
        """)
        self.lua.execute(block + "\nMEMT = MEM; valid_ptr_t = valid_ptr")
        self.lua.execute("MEMT.open = true; MEMT.failed = nil; ptr_value = 0x20000000; int_value = 5")

    def run_lua(self, code):
        return self.lua.eval("(function() local ok, e = pcall(function() " + code + " end); "
                             "return tostring(ok) .. '|' .. tostring(e) end)()")

    def test_string_and_float_addresses_never_reach_native(self):
        for addr in ('"0x20000000"', "2.0^63", "-1", "0", "0xFFFFFFFFFFFFFFFF"):
            self.lua.execute("calls = {}; MEMT.failed = nil")
            r = self.run_lua("return MEMT:ReadShort(%s)" % addr)
            self.assertTrue(r.startswith("false|memory read stopped"), (addr, r))
            self.assertEqual(self.lua.eval("#calls"), 0)

    def test_first_failure_stops_the_tick(self):
        self.run_lua("return MEMT:ReadShort(-1)")
        r = self.run_lua("return MEMT:ReadShort(0x20000000)")
        self.assertTrue(r.startswith("false|memory read stopped"), r)

    def test_bad_pointer_results_become_zero(self):
        for v in ("-1", "0xFFFFFFFFFFFFFFFF", "0x20000004", '"x"', "1.5e19"):
            self.lua.execute("MEMT.failed = nil; ptr_value = %s" % v)
            r = self.run_lua("return MEMT:ReadPointer(0x20000000)")
            self.assertIn(r, ("true|0", "false|memory read stopped: ReadPointer returned string",
                              "false|memory read stopped: ReadPointer returned number"), (v, r))

    def test_non_integer_values_stop(self):
        self.lua.execute("int_value = 'abc'")
        r = self.run_lua("return MEMT:ReadInt(0x20000000)")
        self.assertTrue(r.startswith("false|memory read stopped"), r)

    def test_closed_gate(self):
        self.lua.execute("MEMT.open = false; calls = {}")
        r = self.run_lua("return MEMT:ReadInt(0x20000000)")
        self.assertTrue(r.startswith("false|memory closed"), r)
        self.assertEqual(self.lua.eval("#calls"), 0)

    def test_multilevel_walk_stops_on_bad_level(self):
        self.lua.execute("ptr_value = -1")
        self.assertEqual(self.run_lua("return MEMT:ReadMultilevelPointer(0x20000000, {0x18, 0x10})"), "true|0")


if __name__ == "__main__":
    unittest.main()
